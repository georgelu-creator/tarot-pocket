'use strict'
// Actual academy runtime and learning SFC. uni lifecycle/storage are isolated boundaries.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const { createRequire } = require('node:module')
const { chromium } = require('playwright')
const root = path.resolve(__dirname, '..')
const mini = path.join(root, 'apps/miniapp')
const miniRequire = createRequire(path.join(mini, 'package.json'))
const { parse, compileScript, compileTemplate } = miniRequire('@vue/compiler-sfc')
const filename = path.join(mini, 'src/pages/learn/index.vue')
const { descriptor } = parse(fs.readFileSync(filename, 'utf8'), { filename })
const script = compileScript(descriptor, { id: 'learning-polish' })
const template = compileTemplate({ source: descriptor.template.content, filename, id: 'learning-polish', compilerOptions: { bindingMetadata: script.bindings } })
assert.deepEqual(template.errors, [])
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'tarot-learning-polish-'))
const hooks = path.join(scratch, 'hooks.cjs'), platform = path.join(scratch, 'platform.cjs')
fs.writeFileSync(hooks, 'exports.onShow = cb => {}; exports.onHide = cb => {}; exports.onUnload = cb => {}; exports.onBackPress = cb => window.lessonBack = cb;')
fs.writeFileSync(platform, `exports.readStore = (key, fallback) => window.stores[key] ?? fallback; exports.writeStore = (key, data) => { window.stores[key] = data; window.writes.push({ key, data }); }; exports.notify = text => {}; exports.cardImage = id => 'data:image/gif;base64,R0lGODlhAQABAAD/ACwAAAAAAQABAAACADs=';`)
const miniSource = script.content.replace('export default', 'const component =').replace("'../../core/platform'", "'test-platform'") + '\n' + template.code.replace('export function render', 'function render') + `
import { createApp } from 'vue'; component.render = render;
const setup = component.setup; component.setup = (props, context) => { const bindings = setup(props, context); window.lesson = bindings; return bindings };
createApp(component).mount('#app');`
let bundle
try {
 bundle = miniRequire('esbuild').buildSync({ stdin: { contents: miniSource, loader: 'ts', resolveDir: path.dirname(filename) }, bundle: true, platform: 'browser', format: 'iife', write: false, alias: { '@dcloudio/uni-app': hooks, 'test-platform': platform } }).outputFiles[0].text
} finally { fs.unlinkSync(hooks); fs.unlinkSync(platform); fs.rmdirSync(scratch) }
;(async () => {
 const browser = await chromium.launch({ headless: true })
 try {
  const runtimeErrors = []
  const context = await browser.newContext({ viewport: { width: 320, height: 568 } })
  await context.route('https://lesson.test/**', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><div id="app"></div>' }))
  async function webPage(reduced = false) {
   const page = await context.newPage(); page.on('pageerror', error => runtimeErrors.push(error.message)); await page.emulateMedia({ reducedMotion: reduced ? 'reduce' : 'no-preference' }); await page.goto('https://lesson.test/')
   await page.addStyleTag({ content: ':root{--paper:#fffcf7;--ink:#302a32;--line:#dfd4df;--accent:#66506c;--soft:#eee5ee}body{margin:0}.linkbtn{background:none;border:0}' + fs.readFileSync(path.join(root, 'academy.css'), 'utf8') })
   for (const file of ['academy-content.js', 'academy.js']) await page.addScriptTag({ content: fs.readFileSync(path.join(root, file), 'utf8') })
   await page.evaluate(() => {
    window.learningData = window.TarotAcademy.blank()
    const esc = text => String(text ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]))
    window.academyUI = window.TarotAcademy.create({ esc, icon: () => '', img: id => '<img alt="' + id + '" src="data:image/gif;base64,R0lGODlhAQABAAD/ACwAAAAAAQABAAACADs=">', get: () => window.learningData, set: d => { window.learningData = d }, now: () => 1000000, toast: () => {}, go: () => { document.querySelector('#app').innerHTML = window.academyUI.render() } })
    window.academyUI.start('m00', 'foundation', { courseLevel: 'B' })
   })
   return page
  }
  const web = await webPage()
  assert.equal(await web.locator('.academy-zoom-tip').count(), 1)
  assert.equal(await web.locator('.academy-zoom-tip').isVisible(), false, 'compact first teaching reserves space for its core task')
  await web.setViewportSize({ width: 390, height: 844 })
  assert.equal(await web.locator('.academy-zoom-tip').isVisible(), true, 'larger lesson viewport exposes the dismissible guidance')
  const beforeTip = await web.evaluate(() => JSON.stringify(window.learningData))
  await web.locator('[data-academy="dismiss-zoom-tip"]').click()
  assert.equal(await web.locator('.academy-zoom-tip').count(), 0)
  assert.equal(await web.evaluate(() => JSON.stringify(window.learningData)), beforeTip, 'guidance preference must not change lesson evidence')
  const secondVisit = await webPage()
  assert.equal(await secondVisit.locator('.academy-zoom-tip').count(), 0, 'dismissal survives another visit')
  await secondVisit.close()
  await web.locator('[data-academy="next"]').click()
  const answer = await web.evaluate(() => { window.originalCard = document.querySelector('.academy-card-face'); const s = window.learningData.session, q = window.TarotAcademy.stepFor(s).question; return { correct: q.correct, index: s.index } })
  await web.locator('[data-academy="answer"][data-value="' + answer.correct + '"]').click()
  assert.equal(await web.locator('.academy-feedback.is-correct').count(), 1)
  assert.equal(await web.locator('.academy-option.correct b').count(), 1)
  assert.equal(await web.locator('[data-academy="hint"]').count(), 0)
  assert.equal(await web.evaluate(() => document.querySelector('.academy-card-face') === window.originalCard), true, 'answer must keep the existing card node')
  assert.equal(await web.evaluate(() => window.learningData.session.index), answer.index, 'feedback waits for explicit continue')
  await web.locator('.academy-feedback [data-academy="next"]').click()
  assert.equal(await web.locator('.academy-complete').count(), 1)
  assert.equal(await web.locator('[data-academy="guided"]').count(), 1)
  await web.close()
  const reduced = await webPage(true)
  assert.equal(await reduced.locator('.academy-copy').evaluate(el => getComputedStyle(el).animationName), 'none', 'reduced motion preserves lesson content without transition')
  await reduced.close(); await context.close()

  const page = await browser.newPage({ viewport: { width: 320, height: 568 } })
  page.on('pageerror', error => runtimeErrors.push(error.message))
  await page.setContent('<div id="app"></div>')
  await page.addStyleTag({ content: 'view,scroll-view{display:block}image{display:inline-block}body{margin:0}' + descriptor.styles.map(s => s.content).join('\n').replace(/([\d.]+)rpx/g, (_, n) => Number(n) / 2 + 'px') })
  await page.evaluate(() => { window.stores = {}; window.writes = [] })
  await page.addScriptTag({ content: bundle })
  assert.deepEqual(runtimeErrors, [], 'the actual lesson SFC mounts without runtime errors')
  assert.equal(await page.evaluate(() => typeof window.lessonBack), 'function', 'the uni parent-return lifecycle boundary is registered')
  await page.evaluate(() => window.lesson.start({ id: 'm00', mode: 'foundation' }))
  assert.equal(await page.locator('.zoom-tip').count(), 1)
  const miniBeforeTip = await page.evaluate(() => JSON.stringify(window.lesson.data.value))
  await page.locator('.zoom-tip button').dispatchEvent('tap')
  assert.equal(await page.evaluate(() => JSON.stringify(window.lesson.data.value)), miniBeforeTip)
  assert.deepEqual(await page.evaluate(() => window.writes.at(-1)), { key: 'tarot-miniapp-academy-zoom-tip-v1', data: true }, 'guidance writes its own preference key')
  await page.evaluate(() => window.lesson.nextStep())
  const wrong = await page.evaluate(() => { const l = window.lesson; return { choice: l.options.value.find(o => o.id !== l.step.value.question.correct).id, key: l.lessonKey.value, index: l.session.value.index } })
  await page.evaluate(id => window.lesson.choose(id), wrong.choice)
  await page.waitForFunction(() => window.lesson.scrollTarget.value === 'lesson-feedback')
  assert.equal(await page.locator('.feedback.is-incorrect').count(), 1)
  assert.equal(await page.locator('scroll-view').getAttribute('scroll-into-view'), 'lesson-feedback', 'feedback targets the page scroll-view, not window scrolling')
  assert.equal(await page.locator('scroll-view').getAttribute('scroll-with-animation'), 'true')
  assert.equal(await page.evaluate(() => window.lesson.session.value.index), wrong.index)
  assert.equal(await page.evaluate(() => window.lesson.lessonKey.value), wrong.key, 'answer does not replay the whole lesson transition')
  await page.evaluate(() => window.lesson.nextStep())
  assert.notEqual(await page.evaluate(() => window.lesson.lessonKey.value), wrong.key, 'explicit continue changes teaching content')
  assert.equal(await page.evaluate(() => window.lesson.scrollTarget.value), '', 'new lesson step clears feedback scroll target')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await page.locator('.lesson-content').evaluate(el => getComputedStyle(el).animationName), 'none')
  await page.close()
  assert.deepEqual(runtimeErrors, [], 'both lesson surfaces remain free of runtime errors')
  console.log('PASS learning polish: separate persistent guidance, unchanged evidence, retained web card DOM, explicit feedback/continue, Vue scroll-view target and reduced-motion content. Physical WeChat gestures/scroll timing still need device acceptance.')
 } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
